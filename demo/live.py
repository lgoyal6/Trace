"""Bounded visitor queries through Trace's existing local retrieval and grounding.

The corpus is owned synthetic text. No model, user identity, private corpus or
provider is connected. Temporary SQLite state is removed after every request.
"""
from __future__ import annotations

from dataclasses import asdict
import json
from pathlib import Path
from tempfile import TemporaryDirectory

from backend.app.corpus.versioning import paper_hash
from backend.app.verify.grounding import check_grounding
from backend.vectorstore.retrieval import LocalVectorRetriever, _tokens

DOCUMENTS = (
    ("DEMO-1", "Cedar sensor sampling", "The Cedar sensor emits 12 samples per second. Each sample contains a sequence number and a temperature reading.", False),
    ("DEMO-2", "Harbor queue leases", "The Harbor queue grants a 30 second lease. A stale worker cannot acknowledge a message after its lease expires.", False),
    ("DEMO-3", "Orchard catalog versions", "The Orchard catalog keeps 4 immutable versions. A changed source document increments its version and content hash.", False),
    ("DEMO-4", "Summit checkpoint recovery", "The Summit job writes a checkpoint every 20 steps. Recovery restores the latest completed checkpoint before work resumes.", False),
    ("DEMO-5", "Cedar sensor anomaly", "A rare Cedar sensor fault repeats sequence numbers during startup. The controller discards duplicate samples and records the anomaly.", True),
    ("DEMO-6", "Harbor queue recovery", "A rare Harbor queue fault interrupts a worker after delivery. The queue redelivers the unacknowledged message when the lease expires.", True),
)


def run_query(value: object) -> dict:
    if not isinstance(value, dict) or set(value) != {"query", "top_k", "rarity", "claim"}:
        raise ValueError("Expected query, top_k, rarity and claim only")
    query, top_k, rarity, claim = (value[k] for k in ("query", "top_k", "rarity", "claim"))
    if not isinstance(query, str) or not 1 <= len(query.strip()) <= 256:
        raise ValueError("Query must contain 1 to 256 characters")
    if type(top_k) is not int or not 1 <= top_k <= 6 or type(rarity) is not bool:
        raise ValueError("top_k must be 1 to 6 and rarity must be boolean")
    if not isinstance(claim, str) or len(claim) > 512:
        raise ValueError("Claim must contain at most 512 characters")
    with TemporaryDirectory(prefix="trace-public-") as directory:
        root = Path(directory)
        corpus = root / "empty.json"
        corpus.write_text("[]")
        store = LocalVectorRetriever(db_path=root / "index.sqlite3", corpus_path=corpus)
        for doc_id, title, text, rare in DOCUMENTS:
            store.upsert_document(pmid=doc_id, title=title, abstract=text,
                                  condition="synthetic", is_rare=rare,
                                  source_document="owned-demo-corpus", page=1)
        candidates = store.search(query.strip(), top_k=6, apply_rarity=rarity)
        # An explicit lexical gate blocks hash-collision-only matches. It is not
        # calibrated answerability, and no answer is generated by this endpoint.
        query_terms = set(_tokens(query))
        selected = [row for row in candidates if row.score > 0 and
                    query_terms.intersection(_tokens(f"{row.paper.title} {row.paper.abstract}"))][:top_k]
        grounding = check_grounding(claim, selected)
        return {
            "query": query.strip(), "top_k": top_k, "rarity": rarity,
            "status": "candidates" if selected else "no-lexical-evidence",
            "scorer": "Trace LocalVectorRetriever, 256-dimensional word/bigram feature hash",
            "results": [{"citation": i, "id": row.paper.pmid,
                         "title": row.paper.title, "text": row.paper.abstract,
                         "score": row.score, "rarity_multiplier": row.rarity_multiplier,
                         "content_hash": paper_hash(row.paper)} for i, row in enumerate(selected, 1)],
            "grounding": {**grounding.as_dict(), "claims": [asdict(c) for c in grounding.claims]},
            "limits": ["Owned synthetic corpus; no medical evidence or advice.",
                       "Local feature hashing, not MiniLM, Snowflake or hosted inference.",
                       "Lexical gate and claim overlap are not calibrated semantic answerability.",
                       "No identity authentication, private-corpus authorization or generated answer."],
        }
